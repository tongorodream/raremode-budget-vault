'use strict';
const assert = require('assert');
const { priceWindow, priceSummary, priceCards } = require('../src/grocery-price-filters');
const series = (key, unit, rows) => ({ key, unit, months: rows });
const row = (month, amount, cost) => ({ month, amount, cost, purchases: 1, perUnit: cost/100/amount });
const cheap = series('cheap-g', 'g', [row('2026-10', 100, 10000), row('2026-11', 900, 45000)]);
const costly = series('costly-g', 'g', [row('2026-11', 100, 8000)]);
const volume = series('milk-ml', 'ml', [row('2026-11', 1000, 10000)]);
const eggs = series('eggs-pcs', 'pcs', [row('2026-11', 10, 10000)]);
const missing = series('past-g', 'g', [row('2026-10', 1000, 100)]);
const free = series('free-g', 'g', [row('2026-11', 100, 0)]);
const group = (key, values) => ({ key, name: key, series: values });
const groups = [group('costly', [costly]), group('cheap', [cheap]), group('milk', [volume]),
  group('eggs', [eggs]), group('missing', [missing]), group('absent', []), group('free', [free])];
const original = JSON.stringify(groups);
assert.deepStrictEqual(priceWindow('2026-01',3), {start:'2025-11',end:'2026-01',months:3});
assert.strictEqual(priceSummary(cheap,priceWindow('2026-11')).price,500);
assert.strictEqual(priceSummary(cheap,priceWindow('2026-11',3)).price,550, 'weight paid totals by quantities, not monthly mean prices');
assert.strictEqual(priceSummary(missing,priceWindow('2026-11')),null,'old prices must not masquerade as current-month prices');
assert.strictEqual(priceSummary(cheap,priceWindow('2026-09')),null,'no future price leaks backwards');
const asc = priceCards(groups,'2026-11');
assert.deepStrictEqual(asc.cards.map(p=>p.key),['free','cheap','costly','milk','eggs','missing','absent']);
assert.strictEqual(asc.cards[0].primary.summary.price,0,'a real free item is not an unknown price');
const desc = priceCards(groups,'2026-11',{sort:'desc'});
assert.deepStrictEqual(desc.cards.map(p=>p.key),['costly','cheap','free','milk','eggs','missing','absent']);
const mass = priceCards(groups,'2026-11',{measure:'g'});
assert.deepStrictEqual(mass.cards.map(p=>p.key),['free','cheap','costly','missing']);
const allUnits = priceCards([group('cream',[cheap,volume])],'2026-11').cards[0];
assert.deepStrictEqual(allUnits.summaries.map(s=>s.label),['кг','л']);
assert.strictEqual(allUnits.primary.unit,'g','kg and litre prices are not numerically mixed');
const onlyVolume = priceCards([group('cream',[cheap,volume])],'2026-11',{measure:'ml'}).cards[0];
assert.strictEqual(onlyVolume.series.length,1);
assert.strictEqual(onlyVolume.primary.summary.price,100);
assert.strictEqual(priceSummary(eggs,priceWindow('2026-11')).price,10,'eggs remain per piece without an invented mass');
assert.deepStrictEqual(priceCards(groups,'2026-11',{sort:'none'}).cards.map(p=>p.key),groups.map(p=>p.key));
assert.deepStrictEqual(priceCards(groups,'2026-11',{sort:'name'}).cards.map(p=>p.key),groups.map(p=>p.key).sort());
assert.strictEqual(JSON.stringify(groups),original,'filters do not mutate receipt history');
assert.throws(()=>priceWindow('2026-13'));
console.log('PASS grocery price filters — calendar windows, quantity weighting, current-month bounds, ascending/descending sorts, missing/free prices, separate kg/l/pieces and immutable history');
